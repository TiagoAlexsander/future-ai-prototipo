-- TRIGGER PARA CRIPTOGRAFIA DAS SENHAS --

DELIMITER //
CREATE TRIGGER hash_senha
BEFORE INSERT ON USUARIO 
FOR EACH ROW
BEGIN
IF CHAR_LENGTH(NEW.SENHA) < 60 THEN
SET NEW.SENHA = SHA2(NEW.SENHA, 256);
END IF;
END //
DELIMITER ;